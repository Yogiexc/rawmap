import type { Node } from '@xyflow/react';
import type { NodeData } from '../components/SchemaNode';

/**
 * Generate Prisma Schema (.prisma) from nodes
 */
export function generatePrismaSchema(nodes: Node<NodeData>[]): string {
  let output = `// Prisma Schema generated by RawMap (https://rawmap.vercel.app)\n\n`;
  output += `datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n\ngenerator client {\n  provider = "prisma-client-js"\n}\n\n`;

  nodes.forEach((node) => {
    // Model name: PascalCase and sanitize
    const rawTitle = node.data.label || 'Entity';
    const modelName = toPascalCase(rawTitle);

    output += `model ${modelName} {\n`;

    const fields = node.data.fields || [];
    fields.forEach((field) => {
      const fieldName = sanitizeIdentifier(field.name);
      let prismaType = mapToPrismaType(field.type);
      let attributes = '';

      if (field.isPK) {
        attributes += ' @id';
        if (prismaType === 'Int') {
          attributes += ' @default(autoincrement())';
        } else if (prismaType === 'String') {
          attributes += ' @default(cuid())';
        }
      }

      if (field.isFK) {
        attributes += ` // Foreign Key relation`;
      }

      output += `  ${fieldName.padEnd(16)} ${prismaType}${attributes}\n`;
    });

    output += `}\n\n`;
  });

  return output.trim();
}

/**
 * Generate Drizzle ORM Schema (schema.ts) from nodes
 */
export function generateDrizzleSchema(nodes: Node<NodeData>[]): string {
  let output = `// Drizzle ORM Schema generated by RawMap (https://rawmap.vercel.app)\n`;
  output += `import { pgTable, serial, text, integer, boolean, timestamp, numeric } from 'drizzle-orm/pg-core';\n\n`;

  nodes.forEach((node) => {
    const rawTitle = node.data.label || 'entity';
    const tableName = sanitizeSnakeCase(rawTitle);
    const tableVar = sanitizeCamelCase(rawTitle);

    output += `export const ${tableVar} = pgTable('${tableName}', {\n`;

    const fields = node.data.fields || [];
    fields.forEach((field) => {
      const colName = sanitizeSnakeCase(field.name);
      const colProp = sanitizeCamelCase(field.name);
      const drizzleType = mapToDrizzleColumn(field.type, colName, field.isPK);

      output += `  ${colProp}: ${drizzleType},\n`;
    });

    output += `});\n\n`;
  });

  return output.trim();
}

/**
 * Generate TypeScript Interfaces (.d.ts) from nodes
 */
export function generateTypeScriptInterfaces(nodes: Node<NodeData>[]): string {
  let output = `/**\n * TypeScript Interfaces generated by RawMap\n * https://rawmap.vercel.app\n */\n\n`;

  nodes.forEach((node) => {
    const interfaceName = toPascalCase(node.data.label || 'Entity');
    output += `export interface ${interfaceName} {\n`;

    const fields = node.data.fields || [];
    fields.forEach((field) => {
      const propName = sanitizeIdentifier(field.name);
      const tsType = mapToTypeScriptType(field.type);
      const optional = field.isPK ? '' : '?';

      output += `  ${propName}${optional}: ${tsType};\n`;
    });

    output += `}\n\n`;
  });

  return output.trim();
}

/* Helpers */
function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_') || 'field';
}

function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9_]/g, ' ')
    .split(/[\s_]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('') || 'Model';
}

function sanitizeCamelCase(str: string): string {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

function sanitizeSnakeCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .toLowerCase()
    .replace(/_+/g, '_');
}

function mapToPrismaType(typeStr: string): string {
  const t = (typeStr || '').toLowerCase();
  if (t.includes('int')) return 'Int';
  if (t.includes('decimal') || t.includes('numeric') || t.includes('float') || t.includes('double')) return 'Float';
  if (t.includes('bool')) return 'Boolean';
  if (t.includes('time') || t.includes('date')) return 'DateTime';
  if (t.includes('json')) return 'Json';
  return 'String';
}

function mapToDrizzleColumn(typeStr: string, colName: string, isPK?: boolean): string {
  const t = (typeStr || '').toLowerCase();
  if (isPK && t.includes('int')) return `serial('${colName}').primaryKey()`;
  if (t.includes('int')) return `integer('${colName}')`;
  if (t.includes('decimal') || t.includes('numeric')) return `numeric('${colName}', { precision: 10, scale: 2 })`;
  if (t.includes('bool')) return `boolean('${colName}').default(false)`;
  if (t.includes('time') || t.includes('date')) return `timestamp('${colName}').defaultNow()`;
  return `text('${colName}')`;
}

function mapToTypeScriptType(typeStr: string): string {
  const t = (typeStr || '').toLowerCase();
  if (t.includes('int') || t.includes('number') || t.includes('decimal') || t.includes('float')) return 'number';
  if (t.includes('bool')) return 'boolean';
  if (t.includes('time') || t.includes('date')) return 'Date | string';
  if (t.includes('array')) return 'any[]';
  if (t.includes('object') || t.includes('json')) return 'Record<string, any>';
  return 'string';
}
